function renderMessageHTML(msg) {
	const preProcessed = preRenderTex(msg.content || "");
	const dirty = md.render(preProcessed);
	const clean = DOMPurify.sanitize(dirty, {
		ADD_TAGS: ["span"],
		ADD_ATTR: ["class", "style"],
	});
	const safeName = DOMPurify.sanitize(msg.name || "Anonymous", {
		ALLOWED_TAGS: [],
		ALLOWED_ATTR: [],
	});
	const safeTime = DOMPurify.sanitize(msg.time || "", {
		ALLOWED_TAGS: [],
		ALLOWED_ATTR: [],
	});
	const profileUser = msg.user || "";
	const nameHTML = profileUser
		? "<a class='cname' href='user.html?u=" + encodeURIComponent(profileUser) + "' target='_top'>" + safeName + "</a>"
		: "<span class='cname'>" + safeName + "</span>";
	return (
		"<br><div class='crow'><span class='call'>" +
		nameHTML +
		"<div class='ctime'>" +
		safeTime +
		"</div></span><div class='ccontent'>" +
		clean +
		"</div></div>"
	);
}

